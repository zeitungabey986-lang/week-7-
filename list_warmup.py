# Create a list containing four fruits
fruits = ["mango", "banana", "orange", "apple"]

# Print the first and last fruit
print("First fruit:", fruits[0])
print("Last fruit:", fruits[-1])

# Add a fifth fruit
fruits.append("grapes")
print("After adding a fruit:", fruits)

# Remove one fruit
fruits.remove("banana")
print("After removing a fruit:", fruits)

# Print the number of remaining fruits
print("Number of fruits:", len(fruits))


